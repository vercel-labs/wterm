#!/usr/bin/env node

/**
 * Generates src/grapheme_break_table.zig and src/grapheme_break_test_data.zig
 * from the Unicode Character Database: Grapheme_Cluster_Break,
 * Extended_Pictographic, and Indic_Conjunct_Break, plus the official
 * GraphemeBreakTest.txt cases.
 *
 * Run by hand when Unicode publishes a new version: bump UNICODE_VERSION and
 * regenerate, together with scripts/gen-unicode-width.mjs.
 */

import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const UNICODE_VERSION = "17.0.0";
const BASE = `https://www.unicode.org/Public/${UNICODE_VERSION}/ucd`;
const MAX_CODEPOINT = 0x10ffff;

// Must match `Gcb` in src/grapheme.zig.
const GCB = [
  "Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator",
  "Prepend", "SpacingMark", "L", "V", "T", "LV", "LVT",
];
const EXT_PICT = 0x10;
const INCB = { Consonant: 0x20, Extend: 0x40, Linker: 0x60 };

async function fetchText(path) {
  const url = `${BASE}/${path}`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`fetching ${url} returned ${response.status}`);
  return response.text();
}

/** Yields [start, end, fields] for each data line of a UCD property file. */
function* entries(text) {
  for (const line of text.split("\n")) {
    const body = line.split("#")[0].trim();
    if (!body) continue;
    const fields = body.split(";").map((s) => s.trim());
    const [startHex, endHex] = fields[0].split("..");
    const start = Number.parseInt(startHex, 16);
    yield [start, endHex ? Number.parseInt(endHex, 16) : start, fields.slice(1)];
  }
}

function properties(gcbText, emojiText, derivedText) {
  const props = new Uint8Array(MAX_CODEPOINT + 1);
  for (const [s, e, [name]] of entries(gcbText)) {
    const value = GCB.indexOf(name);
    if (value < 0) throw new Error(`unknown Grapheme_Cluster_Break ${name}`);
    for (let cp = s; cp <= e; cp++) props[cp] = value;
  }
  for (const [s, e, [name]] of entries(emojiText)) {
    if (name !== "Extended_Pictographic") continue;
    for (let cp = s; cp <= e; cp++) props[cp] |= EXT_PICT;
  }
  for (const [s, e, [name, value]] of entries(derivedText)) {
    if (name !== "InCB") continue;
    if (!(value in INCB)) throw new Error(`unknown InCB ${value}`);
    for (let cp = s; cp <= e; cp++) props[cp] |= INCB[value];
  }
  return props;
}

/** Runs of equal properties, as their start code points; each run ends where the next begins. */
function runs(props) {
  const out = [];
  for (let cp = 0; cp <= MAX_CODEPOINT; cp++) {
    if (cp === 0 || props[cp] !== props[cp - 1]) out.push([cp, props[cp]]);
  }
  return out;
}

function tests(text) {
  const out = [];
  for (const line of text.split("\n")) {
    const body = line.split("#")[0].trim();
    if (!body) continue;
    // "÷ 0020 × 0308 ÷": a list of code points and whether a break precedes each.
    const tokens = body.split(/\s+/);
    const cps = [];
    const breaks = [];
    for (let i = 1; i < tokens.length - 1; i += 2) {
      cps.push(Number.parseInt(tokens[i], 16));
      breaks.push(tokens[i - 1] === "÷");
    }
    out.push({ cps, breaks });
  }
  return out;
}

const hex = (n) => n.toString(16).toUpperCase().padStart(4, "0");
const header = (what) => `// Generated by scripts/gen-grapheme-break.mjs from Unicode ${UNICODE_VERSION}.
// Do not edit by hand. Regenerate with:
//   node scripts/gen-grapheme-break.mjs
//
// ${what}
`;

async function main() {
  const here = dirname(fileURLToPath(import.meta.url));
  const [gcb, emoji, derived, testText] = await Promise.all([
    fetchText("auxiliary/GraphemeBreakProperty.txt"),
    fetchText("emoji/emoji-data.txt"),
    fetchText("DerivedCoreProperties.txt"),
    fetchText("auxiliary/GraphemeBreakTest.txt"),
  ]);

  const table = runs(properties(gcb, emoji, derived));
  writeFileSync(
    join(here, "..", "src", "grapheme_break_table.zig"),
    `${header("Each entry is (first code point << 8) | properties, for a run of code points\n// that share them up to the next entry. Properties: bits 0-3\n// Grapheme_Cluster_Break, bit 4 Extended_Pictographic, bits 5-6\n// Indic_Conjunct_Break. Sorted, so a binary search is valid.")}
pub const runs = [_]u32{
${table.map(([s, p]) => `    0x${hex(s)}${p.toString(16).padStart(2, "0")},`).join("\n")}
};
`,
  );

  const cases = tests(testText);
  writeFileSync(
    join(here, "..", "src", "grapheme_break_test_data.zig"),
    `${header("Cases from GraphemeBreakTest.txt. `breaks[i]` says whether a cluster\n// boundary precedes `cps[i]`. Referenced only by tests.")}
pub const Case = struct { cps: []const u21, breaks: []const bool };

pub const cases = [_]Case{
${cases.map(({ cps, breaks }) => `    .{ .cps = &.{ ${cps.map((c) => `0x${hex(c)}`).join(", ")} }, .breaks = &.{ ${breaks.join(", ")} } },`).join("\n")}
};
`,
  );
  console.log(`Wrote ${table.length} property runs and ${cases.length} test cases`);
}

await main();
