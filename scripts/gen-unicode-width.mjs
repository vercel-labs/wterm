#!/usr/bin/env node

/**
 * Generates src/unicode_width_table.zig from the Unicode Character Database.
 *
 * A codepoint is wide when EastAsianWidth.txt gives it W or F, or when it is
 * unlisted and falls in one of the blocks that file documents as defaulting to
 * W. Everything else is narrow, including unassigned codepoints outside those
 * blocks: hand-written block ranges classified 1209 assigned characters as
 * wide that Unicode calls narrow.
 *
 * Run by hand when Unicode publishes a new version: bump UNICODE_VERSION and
 * regenerate.
 */

import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const UNICODE_VERSION = "17.0.0";
const EAW_URL = `https://www.unicode.org/Public/${UNICODE_VERSION}/ucd/EastAsianWidth.txt`;

/** Documented in EastAsianWidth.txt: unassigned codepoints here default to W. */
const DEFAULT_WIDE_BLOCKS = [
  [0x3400, 0x4dbf], // CJK Unified Ideographs Extension A
  [0x4e00, 0x9fff], // CJK Unified Ideographs
  [0xf900, 0xfaff], // CJK Compatibility Ideographs
  [0x20000, 0x2fffd], // Plane 2
  [0x30000, 0x3fffd], // Plane 3
];

const MAX_CODEPOINT = 0x10ffff;

function parseEastAsianWidth(text) {
  const wide = [];
  const listed = [];
  for (const line of text.split("\n")) {
    const body = line.split("#")[0].trim();
    if (!body) continue;
    const [range, klass] = body.split(";").map((s) => s.trim());
    if (!range || !klass) continue;
    const [startHex, endHex] = range.split("..");
    const start = Number.parseInt(startHex, 16);
    const end = endHex ? Number.parseInt(endHex, 16) : start;
    listed.push([start, end]);
    if (klass === "W" || klass === "F") wide.push([start, end]);
  }
  if (wide.length === 0) throw new Error("no W/F ranges parsed");
  return { wide, listed };
}

/** Default-wide blocks only apply where the file says nothing. */
function unlistedWithin(block, listed) {
  const [blockStart, blockEnd] = block;
  const covering = listed
    .filter(([s, e]) => e >= blockStart && s <= blockEnd)
    .sort((a, b) => a[0] - b[0]);
  const gaps = [];
  let cursor = blockStart;
  for (const [s, e] of covering) {
    if (s > cursor) gaps.push([cursor, s - 1]);
    cursor = Math.max(cursor, e + 1);
  }
  if (cursor <= blockEnd) gaps.push([cursor, blockEnd]);
  return gaps;
}

function merge(ranges) {
  const sorted = [...ranges].sort((a, b) => a[0] - b[0]);
  const out = [];
  for (const [start, end] of sorted) {
    const last = out[out.length - 1];
    if (last && start <= last[1] + 1) {
      last[1] = Math.max(last[1], end);
    } else {
      out.push([start, end]);
    }
  }
  return out;
}

function render(ranges) {
  const rows = ranges
    .map(([s, e]) => `    .{ 0x${hex(s)}, 0x${hex(e)} },`)
    .join("\n");
  return `// Generated by scripts/gen-unicode-width.mjs from Unicode ${UNICODE_VERSION}.
// Do not edit by hand. Regenerate with:
//   node scripts/gen-unicode-width.mjs
//
// Inclusive ranges of codepoints whose East_Asian_Width is W or F, plus the
// unassigned codepoints in the blocks EastAsianWidth.txt documents as
// defaulting to W. Sorted and merged, so a binary search is valid.

pub const wide_ranges = [_][2]u21{
${rows}
};
`;
}

const hex = (n) => n.toString(16).toUpperCase().padStart(4, "0");

async function main() {
  const here = dirname(fileURLToPath(import.meta.url));
  const outPath = join(here, "..", "src", "unicode_width_table.zig");

  const response = await fetch(EAW_URL);
  if (!response.ok) {
    throw new Error(`fetching ${EAW_URL} returned ${response.status}`);
  }
  const { wide, listed } = parseEastAsianWidth(await response.text());

  const defaults = DEFAULT_WIDE_BLOCKS.flatMap((block) =>
    unlistedWithin(block, listed),
  );
  const ranges = merge([...wide, ...defaults]).filter(
    ([s]) => s <= MAX_CODEPOINT,
  );
  const rendered = render(ranges);

  writeFileSync(outPath, rendered);
  console.log(`Wrote ${ranges.length} wide ranges to ${outPath}`);
}

await main();
